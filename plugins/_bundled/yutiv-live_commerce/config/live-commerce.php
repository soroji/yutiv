<?php

/**
 * TeeWide 라이브커머스 설정.
 *
 * 이 배열은 `LiveCommerceServiceProvider::register()` 에서 `yutiv_live_commerce` 키로
 * 머지된다. 값은 전부 `.env` 에서 읽으며, **기본값은 완전 비활성**이다.
 *
 *   TEEWIDE_ENABLED=false  → 라우트도 미들웨어도 세션 변경도 일어나지 않는다.
 *
 * 즉 플러그인을 설치·활성화만 해도 기존 yutiv.com 은 아무 영향을 받지 않는다.
 * config:cache 를 쓰는 운영을 고려해 `env()` 호출은 이 파일 안에서만 한다.
 */
return [

    /*
    |--------------------------------------------------------------------------
    | 기능 스위치
    |--------------------------------------------------------------------------
    |
    | 기본 false. TeeWide 도메인·DNS·인증서가 준비되고 운영자가 명시적으로 켤 때까지
    | 이 플러그인은 아무 것도 등록하지 않는다.
    |
    */
    'enabled' => (bool) env('TEEWIDE_ENABLED', false),

    /*
    |--------------------------------------------------------------------------
    | 호스트
    |--------------------------------------------------------------------------
    |
    | root_host  계정 포털 — 로그인/회원가입/내 정보만 제공한다.
    | live_host  라이브 판매 — /{tenant_slug} 로만 접근한다.
    |
    | ※ route:cache 를 쓰면 이 값이 컴파일된 라우트에 박힌다. 호스트를 바꾼 뒤에는
    |   반드시 `php artisan route:cache` 를 다시 실행해야 한다.
    |
    */
    'root_host' => env('TEEWIDE_ROOT_HOST', 'teewide.com'),
    'live_host' => env('TEEWIDE_LIVE_HOST', 'live.teewide.com'),

    /*
    |--------------------------------------------------------------------------
    | 세션
    |--------------------------------------------------------------------------
    |
    | TeeWide 는 기존 YUTIV 세션과 **완전히 분리된** 쿠키를 쓴다.
    |   cookie  이름이 다르므로 같은 브라우저에서도 서로를 읽지 못한다.
    |   domain  `.teewide.com` 이라 teewide.com 과 live.teewide.com 이 공유한다.
    |           yutiv.com 으로는 브라우저가 이 쿠키를 보내지 않는다.
    |
    */
    'session' => [
        'cookie' => env('TEEWIDE_SESSION_COOKIE', 'teewide_session'),
        'domain' => env('TEEWIDE_SESSION_DOMAIN', '.teewide.com'),
    ],

    /*
    |--------------------------------------------------------------------------
    | 차단 응답
    |--------------------------------------------------------------------------
    |
    | TeeWide 호스트에서 YUTIV 콘텐츠 요청이 오면 404 로 끝낸다.
    | 리다이렉트를 쓰지 않는 이유: 리다이렉트는 목적지를 알려주는 정보 노출이고,
    | Host 기반 URL 생성과 얽히면 open redirect 표면이 된다.
    |
    */
    'block_status' => 404,

    /*
    |--------------------------------------------------------------------------
    | 진단 라우트 (Phase 0 스파이크 전용)
    |--------------------------------------------------------------------------
    |
    | 도메인 격리를 증명하기 위한 최소 JSON 응답이다. 실제 UI 가 아니며,
    | Phase 1 에서 실제 포털·라이브 화면으로 대체된다.
    |
    */
    'diagnostics_enabled' => (bool) env('TEEWIDE_DIAGNOSTICS', true),

    // tenant slug 형식 — 소문자·숫자·하이픈만. 라우트 제약과 검증에 함께 쓴다.
    'tenant_slug_pattern' => '[a-z0-9][a-z0-9-]{0,62}',

    // Phase 0 에서 인식하는 tenant. Phase 1 에서 DB(live_tenants)로 대체된다.
    'known_tenants' => ['golfif'],
];
